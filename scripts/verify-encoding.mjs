import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'

const browser = process.env.CDP_URL
  ? await chromium.connectOverCDP(process.env.CDP_URL)
  : await chromium.launch({ executablePath: process.env.BROWSER_PATH ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
const context = process.env.CDP_URL ? browser.contexts()[0] : await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = process.env.CDP_URL ? context.pages()[0] : await context.newPage()
if (!process.env.CDP_URL) await page.goto('http://127.0.0.1:1420')
const failures = []
const observations = []
page.on('pageerror', error => failures.push(error.message))
await mkdir('artifacts', { recursive: true })
const input = page.getByRole('textbox', { name: '编码输入内容', exact: true })
const output = page.getByRole('textbox', { name: '编码转换结果', exact: true })
const tab = name => page.getByRole('tab', { name, exact: true }).click()
const button = name => page.getByRole('button', { name, exact: true }).click()
async function expectValue(locator, value) {
  await page.waitForFunction(({ label, value }) => document.querySelector(`[aria-label="${label}"]`)?.value === value, { label: await locator.getAttribute('aria-label'), value })
  assert.equal(await locator.inputValue(), value)
}
async function roundtrip(tool, text, encode, decode, expected) {
  await tab(tool)
  await input.fill(text)
  await button(encode)
  if (expected !== undefined) await expectValue(output, expected)
  const encoded = await output.inputValue()
  assert(encoded.length > 0)
  await button('交换内容')
  await button(decode)
  await expectValue(output, text)
  observations.push(`${tool} 编码/解码 → 原文本完整还原`)
}
try {
  await tab('计算器')
  const calculator = page.getByRole('textbox', { name: '计算表达式', exact: true })
  const savedExpression = await calculator.inputValue()
  await calculator.fill('0xFF + 1')
  await tab('编码工具')
  await roundtrip('Unicode 编码', '中文😀', 'ASCII 转 Unicode', 'Unicode 转 ASCII', '\\u4e2d\\u6587\\ud83d\\ude00')
  await input.fill('Hello 中文')
  await button('中文转 Unicode')
  assert.match(await output.inputValue(), /^Hello \\u4e2d\\u6587$/i)
  await roundtrip('UTF-8 编码', '中文😀', 'UTF-8 编码', 'UTF-8 解码', 'E4 B8 AD E6 96 87 F0 9F 98 80')
  await input.fill('FF')
  await button('UTF-8 解码')
  assert.match(await page.getByRole('alert').textContent(), /UTF-8|字节/)
  await input.fill('0xE4 0xB8 0xAD')
  await button('UTF-8 解码')
  await expectValue(output, '中')
  observations.push('UTF-8非法FF字节 → 清晰错误；0x格式可解码')
  await roundtrip('URL 编码/解码', '中文 + &=', 'URL 编码', 'URL 解码', '%E4%B8%AD%E6%96%87%20%2B%20%26%3D')
  await page.getByLabel('URL 编码模式', { exact: true }).selectOption('form')
  await input.fill('a b+c')
  await button('URL 编码')
  await expectValue(output, 'a+b%2Bc')
  await input.fill('%ZZ')
  await button('URL 解码')
  assert(await page.getByRole('alert').isVisible())
  await roundtrip('ASCII / Native', 'name=中文😀', 'Native 转 ASCII', 'ASCII 转 Native', 'name=\\u4e2d\\u6587\\ud83d\\ude00')
  await roundtrip('Hex 编码/解码', '中文', 'Hex 编码', 'Hex 解码', 'e4b8ade69687')
  await roundtrip('HTML 编码/解码', '<b title="中">A&B</b>', 'HTML 编码', 'HTML 解码')
  await input.fill('&copy; &#20013; &#x1F600; &lt;script&gt;')
  await button('HTML 解码')
  await expectValue(output, '© 中 😀 <script>')
  observations.push('HTML命名实体/数字实体解码 → 纯文本结果，无脚本执行')
  await roundtrip('Base64', '中文😀', 'Base64 编码', 'Base64 解码', Buffer.from('中文😀').toString('base64'))
  await page.getByLabel('Base64 URL 安全模式', { exact: true }).check()
  await input.fill('中文😀')
  await button('Base64 编码')
  await expectValue(output, Buffer.from('中文😀').toString('base64url'))
  await tab('Base 编码/解码')
  for (const [variant, expected] of [['base16', '666F6F'], ['base32', 'MZXW6==='], ['base58', 'bQbp']]) {
    await page.getByLabel('Base 编码类型', { exact: true }).selectOption(variant)
    await input.fill('foo')
    await button('编码')
    await expectValue(output, expected)
    await button('交换内容')
    await button('解码')
    await expectValue(output, 'foo')
  }
  observations.push('Base16 / Base32 / Base58 标准向量foo → 编码/解码正确')
  await tab('计算器')
  assert.equal(await calculator.inputValue(), '0xFF + 1')
  await calculator.fill(savedExpression)
  await tab('编码工具')
  assert.equal(await input.inputValue(), 'bQbp')
  await page.screenshot({ path: 'artifacts/encoding-tools.png', fullPage: true })
  await tab('Unicode 编码')
  assert.equal(await input.inputValue(), 'Hello 中文')
  observations.push('一级Tab和编码分类切换 → 各自输入和结果保留')
  await tab('Unix 时间戳')
  await page.getByLabel('时间显示时区', { exact: true }).selectOption('utc')
  await page.getByLabel('待转换时间戳', { exact: true }).fill('0')
  await button('转换为日期')
  await expectValue(page.getByLabel('日期转换结果', { exact: true }), '1970-01-01 00:00:00.000')
  await page.getByLabel('待转换日期时间', { exact: true }).fill('2023-11-14T22:13:20Z')
  await button('转换为时间戳')
  await expectValue(page.getByLabel('时间戳转换结果', { exact: true }), '1700000000')
  await page.getByLabel('输出时间戳单位', { exact: true }).selectOption('milliseconds')
  await expectValue(page.getByLabel('时间戳转换结果', { exact: true }), '1700000000000')
  await page.getByLabel('待转换日期时间', { exact: true }).fill('2024-02-30 12:00:00')
  await button('转换为时间戳')
  assert.match(await page.getByRole('alert').textContent(), /不存在|无效/)
  await page.getByLabel('待转换日期时间', { exact: true }).fill('2024-02-29 12:00:00')
  await button('转换为时间戳')
  await expectValue(page.getByLabel('时间戳转换结果', { exact: true }), '1709208000000')
  await page.screenshot({ path: 'artifacts/timestamp-tool.png', fullPage: true })
  observations.push('Unix时间戳0、1700000000、秒/毫秒、UTC、闰日 → 正确；2月30日被拒绝')
  if (!process.env.CDP_URL) await page.setViewportSize({ width: 960, height: 680 })
  await tab('Unicode 编码')
  await page.screenshot({ path: 'artifacts/encoding-tools-960.png', fullPage: true })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth))
  assert.deepEqual(failures, [])
  await writeFile('artifacts/encoding-verification.json', JSON.stringify({ verdict: 'PASS', observations }, null, 2))
  console.log(JSON.stringify({ verdict: 'PASS', observations }, null, 2))
} catch (error) {
  await page.screenshot({ path: 'artifacts/encoding-failure.png', fullPage: true }).catch(() => {})
  throw error
} finally { await browser.close() }
