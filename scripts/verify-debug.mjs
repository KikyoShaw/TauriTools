import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'

const desktop = !!process.env.CDP_URL
const browser = desktop ? await chromium.connectOverCDP(process.env.CDP_URL) : await chromium.launch({ executablePath: process.env.BROWSER_PATH ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
const context = desktop ? browser.contexts()[0] : await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = desktop ? context.pages().find(item => /localhost|127\.0\.0\.1/.test(item.url())) ?? context.pages()[0] : await context.newPage()
if (!desktop) await page.goto(process.env.APP_URL ?? 'http://127.0.0.1:1420')
await mkdir('artifacts', { recursive: true })
await mkdir('docs/images', { recursive: true })
const failures = []
const observations = []
function record(message) { observations.push(message); console.log(message) }
page.on('pageerror', error => failures.push(error.message))
const button = name => page.getByRole('button', { name, exact: true }).click()
const tab = name => page.getByRole('tab', { name, exact: true }).click()
async function expectInput(label, expected) {
  await page.waitForFunction(({ label, expected }) => document.querySelector(`[aria-label="${label}"]`)?.value === expected, { label, expected })
  assert.equal(await page.getByLabel(label, { exact: true }).inputValue(), expected)
}
let cdp
try {
  await tab('开发辅助')
  cdp = await context.newCDPSession(page)
  await cdp.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false })
  await tab('文本 / JSON 对比')
  const left = page.getByLabel('对比左侧内容', { exact: true })
  const right = page.getByLabel('对比右侧内容', { exact: true })
  await left.fill('共同内容\n旧内容\n末尾\n')
  await right.fill('共同内容\n新内容\n新增\n末尾\n')
  await button('开始对比')
  assert.match(await page.locator('.diff-status').textContent(), /新增 2 行.*删除 1 行/)
  await button('下一处差异')
  assert.equal(await page.locator('.diff-row-active').count(), 1)
  await left.fill('  alpha   beta\n\n')
  await right.fill('alpha beta\n\n')
  await page.getByLabel('忽略空白差异', { exact: true }).check()
  await button('开始对比')
  assert.match(await page.locator('.diff-status').textContent(), /内容相同/)
  await right.fill('alpha beta\n')
  await button('开始对比')
  assert.match(await page.locator('.diff-status').textContent(), /删除 1 行/)
  await page.getByLabel('对比模式', { exact: true }).selectOption('json')
  await left.fill('{"id":9007199254740993,"number":1e999,"list":[1,2]}')
  await right.fill('{"list":[1,2],"number":10e998,"id":9007199254740994}')
  await button('开始对比')
  assert.match(await page.locator('.diff-status').textContent(), /值变化 1 项/)
  assert.equal(await page.locator('.diff-json-table tbody tr').count(), 1)
  assert.match(await page.locator('.diff-json-table tbody').textContent(), /9007199254740993.*9007199254740994/)
  await right.fill('{"list":[1,2],"number":10e998,"id":9007199254740993}')
  await button('开始对比')
  assert.match(await page.locator('.diff-status').textContent(), /内容相同/)
  await page.getByLabel('忽略对象键顺序', { exact: true }).uncheck()
  await button('开始对比')
  assert.match(await page.locator('.diff-status').textContent(), /键顺序变化 1 项/)
  await right.fill('{"x":1,"x":2}')
  await button('开始对比')
  assert.match(await page.getByRole('alert').textContent(), /重复键/)
  await page.getByLabel('忽略对象键顺序', { exact: true }).check()
  await button('填入示例')
  await page.getByRole('heading', { name: '开发辅助', exact: true }).click()
  await page.screenshot({ path: 'docs/images/debug-diff.png', fullPage: true, scale: 'css' })
  record('文本行差异与导航、空白/空行、JSON路径、大整数与精确指数、键顺序、重复键报错 → 正常')

  await tab('哈希与文件校验')
  const hashText = page.getByLabel('哈希文本内容', { exact: true })
  await hashText.fill('abc')
  await button('计算哈希')
  await expectInput('SHA-256 摘要', createHash('sha256').update('abc').digest('hex'))
  for (const [algorithm, label] of [['md5', 'MD5'], ['sha1', 'SHA-1'], ['sha256', 'SHA-256'], ['sha512', 'SHA-512']]) {
    assert.equal(await page.getByLabel(`${label} 摘要`, { exact: true }).inputValue(), createHash(algorithm).update('abc').digest('hex'))
  }
  assert.equal(await page.getByLabel('CRC32 摘要', { exact: true }).inputValue(), '352441c2')
  await page.getByLabel('预期校验值', { exact: true }).fill(' ' + createHash('sha256').update('abc').digest('hex').toUpperCase() + ' ')
  assert.equal(await page.locator('.hash-comparison').textContent(), '校验一致')
  await page.getByLabel('预期校验值', { exact: true }).fill('0'.repeat(64))
  assert.equal(await page.locator('.hash-comparison').textContent(), '校验不一致')
  await page.getByLabel('预期校验值', { exact: true }).fill('wrong')
  assert.match(await page.locator('.hash-verify [aria-invalid="true"]').getAttribute('aria-label'), /预期校验值/)
  await hashText.fill('')
  assert.equal(await page.getByLabel('MD5 摘要', { exact: true }).inputValue(), '')
  await button('计算哈希')
  await expectInput('MD5 摘要', createHash('md5').update('').digest('hex'))
  assert.equal(await page.getByLabel('CRC32 摘要', { exact: true }).inputValue(), '00000000')
  const hashSample = 'Kikyo 本地哈希 👋\n保留首尾空白  '
  await hashText.fill(hashSample)
  await button('计算哈希')
  await expectInput('SHA-256 摘要', createHash('sha256').update(hashSample).digest('hex'))
  await page.getByLabel('预期校验值', { exact: true }).fill(createHash('sha256').update(hashSample).digest('hex'))
  await button('复制 SHA-256')
  await page.locator('.hash-toast').waitFor()
  assert.match(await page.locator('.hash-toast').textContent(), /已复制/)
  await page.locator('.hash-toast').waitFor({ state: 'hidden' })
  await page.getByRole('heading', { name: '开发辅助', exact: true }).click()
  await page.screenshot({ path: 'docs/images/debug-hash.png', fullPage: true, scale: 'css' })
  record('五种哈希abc标准向量、空文本、UTF-8中文、大小写校验/不匹配/非法摘要、复制 → 正确')
  await button('文件校验')
  const fileContent = Buffer.alloc(3 * 1024 * 1024 + 123, 0x61)
  await page.getByLabel('选择校验文件', { exact: true }).setInputFiles({ name: 'local-file.bin', mimeType: 'application/octet-stream', buffer: fileContent })
  await button('计算哈希')
  await expectInput('SHA-256 摘要', createHash('sha256').update(fileContent).digest('hex'))
  assert.equal(await page.getByLabel('MD5 摘要', { exact: true }).inputValue(), createHash('md5').update(fileContent).digest('hex'))
  await page.getByLabel('选择校验文件', { exact: true }).setInputFiles({ name: 'empty.bin', mimeType: 'application/octet-stream', buffer: Buffer.alloc(0) })
  await button('计算哈希')
  await expectInput('SHA-256 摘要', createHash('sha256').update('').digest('hex'))
  await page.getByLabel('选择校验文件', { exact: true }).evaluate(input => {
    const transfer = new DataTransfer()
    transfer.items.add(new File([new Uint8Array(16 * 1024 * 1024).fill(0x62)], 'cancel.bin'))
    input.files = transfer.files
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await button('计算哈希')
  await button('取消计算')
  assert.match(await page.locator('.hash-actions + p, .hash-tool > [role="status"]').textContent(), /取消/)
  assert.equal(await page.getByLabel('SHA-256 摘要', { exact: true }).inputValue(), '')
  record('3 MiB以上文件分块摘要、空文件、取消文件计算 → 与文件字节校验值一致，取消不残留结果')

  await tab('正则调试')
  const pattern = page.getByLabel('正则表达式', { exact: true })
  const regexText = page.getByLabel('正则测试文本', { exact: true })
  const replacement = page.getByLabel('正则替换内容', { exact: true })
  const replaced = page.locator('textarea[aria-label="正则替换结果"]')
  async function runRegex(source, text, substitute = '') {
    await pattern.fill(source)
    await regexText.fill(text)
    await replacement.fill(substitute)
    await button('运行匹配')
  }
  await runRegex('(?<name>[A-Za-z]+)=(\\d+)', 'width=1280\nheight=720', '$<name>: $2')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('找到 2 处匹配'))
  assert.equal(await replaced.inputValue(), 'width: 1280\nheight: 720')
  assert.equal(await page.locator('.regex-highlight mark').count(), 2)
  assert.match(await page.locator('.regex-match-list').textContent(), /第 2 组.*1280/)
  await page.getByLabel('全局匹配 g', { exact: true }).uncheck()
  await button('运行匹配')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('找到 1 处匹配'))
  assert.equal(await replaced.inputValue(), 'width: 1280\nheight=720')
  await page.getByLabel('全局匹配 g', { exact: true }).check()
  await page.getByLabel('Unicode u', { exact: true }).check()
  await runRegex('(?:)', '😀a', '|')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('找到 3 处匹配'))
  assert.equal(await replaced.inputValue(), '|😀|a|')
  assert.equal(await page.locator('.regex-zero').count(), 3)
  await runRegex('(a)?b', 'b ab', '$1-$&-$$')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('找到 2 处匹配'))
  assert.equal(await replaced.inputValue(), 'b ab'.replace(/(a)?b/gu, '$1-$&-$$'))
  assert.match(await page.locator('.regex-match-list').textContent(), /未参与匹配/)
  record('正则g/u标志、命名/数字捕获组、未参与分组、Unicode零宽匹配和原生替换语法 → 正确')
  await runRegex('[', 'test')
  await page.locator('.regex-error').waitFor()
  assert.match(await page.locator('.regex-error').textContent(), /语法错误/)
  await runRegex('(a+)+$', 'a'.repeat(30) + '!')
  await page.waitForFunction(() => document.querySelector('.regex-error')?.textContent.includes('超过1秒'))
  assert(await pattern.isEnabled())
  await runRegex('a', 'a'.repeat(1001), 'b')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('超过 1000'))
  assert(await page.getByRole('button', { name: '复制替换结果', exact: true }).isDisabled())
  await runRegex('zzz', 'abc')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('未找到匹配'))
  assert.equal(await replaced.inputValue(), 'abc')
  record('非法正则、耗时表达式超时终止、1000处匹配上限和无匹配 → 明确提示且页面保持可用')
  await button('填入示例')
  await page.waitForFunction(() => document.querySelector('.regex-status')?.textContent.includes('找到 3 处匹配'))
  await button('复制替换结果')
  await page.locator('.regex-notice').waitFor()
  assert.match(await page.locator('.regex-notice').textContent(), /已复制/)
  await page.locator('.regex-notice').waitFor({ state: 'hidden' })
  await page.getByRole('heading', { name: '开发辅助', exact: true }).click()
  await page.screenshot({ path: 'docs/images/debug-regex.png', fullPage: true, scale: 'css' })
  const savedPattern = await pattern.inputValue()
  await tab('JSON 工具')
  await tab('开发辅助')
  assert.equal(await pattern.inputValue(), savedPattern)
  await tab('文本 / JSON 对比')
  assert.match(await left.inputValue(), /9007199254740993/)
  if (desktop) await cdp.send('Emulation.setDeviceMetricsOverride', { width: 960, height: 680, deviceScaleFactor: 1, mobile: false })
  else { await cdp.send('Emulation.clearDeviceMetricsOverride'); await page.setViewportSize({ width: 960, height: 680 }) }
  for (const name of ['文本 / JSON 对比', '哈希与文件校验', '正则调试']) {
    await tab(name)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), name + '页面横向溢出')
  }
  await page.screenshot({ path: 'artifacts/debug-960.png', fullPage: true, scale: 'css' })
  record('三级工具状态及主Tab状态保留、960px窗口无页面横向溢出 → 正常')
  assert.deepEqual(failures, [])
  await writeFile('artifacts/debug-verification.json', JSON.stringify({ verdict: 'PASS', desktop, observations }, null, 2))
  console.log(JSON.stringify({ verdict: 'PASS', desktop, observations }, null, 2))
} catch (error) {
  await page.screenshot({ path: 'artifacts/debug-failure.png', fullPage: true }).catch(() => {})
  throw error
} finally {
  if (cdp) await cdp.send('Emulation.clearDeviceMetricsOverride').catch(() => {})
  await browser.close()
}
